#include <stdio.h>

/*
 * Лабораторная работа № 3, п. 2.10 (дополнительно).
 * Проверка Unicode-идентификаторов в C.
 *
 * GCC 10+ принимает UTF-8 буквы в идентификаторах (реализационное
 * расширение; в C23 разрешены UCN, поддержка UTF-8 зависит от компилятора).
 */
int main(void)
{
    int студент = 304;
    int студенты = 30;
    int 学生 = 7;

    printf("студент = %d\n", студент);
    printf("студенты = %d\n", студенты);
    printf("学生 = %d\n", 学生);

    return 0;
}
